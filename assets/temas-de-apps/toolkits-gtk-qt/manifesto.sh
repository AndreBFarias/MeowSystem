# Lê um valor do CosmicTk (formato RON) e devolve sem as aspas.
_meow_tk_ler_tk() {
  local chave="${1:-}" bruto=""
  [ -r "$MEOW_TK_TK_DIR/$chave" ] || return 1
  bruto="$(cat "$MEOW_TK_TK_DIR/$chave" 2>/dev/null)" || return 1
  bruto="${bruto%\"}"; bruto="${bruto#\"}"
  printf '%s' "$bruto"
}

# Lê `chave=valor` da seção [Appearance] de um .conf estilo QSettings.
#
# A chave viaja pelo AMBIENTE, não por `awk -v`: o `-v` processa sequências de
# escape (uma barra invertida no valor vira outra coisa), e `ENVIRON` entrega o
# texto cru. Aqui a chave é literal, mas o mesmo helper serve para valores
# vindos da config dela — o hábito é o que evita a surpresa.
_meow_tk_ini_ler() {
  local arquivo="${1:-}" chave="${2:-}"
  [ -r "$arquivo" ] || return 1
  MEOW_INI_CHAVE="$chave" awk '
    BEGIN { chave = ENVIRON["MEOW_INI_CHAVE"]; achou = 0 }
    /^\[/ { na = ($0 == "[Appearance]"); next }
    na && index($0, chave "=") == 1 { print substr($0, length(chave) + 2); achou = 1; exit }
    END { if (!achou) exit 1 }
  ' "$arquivo"
}

# Devolve no stdout o conteúdo do arquivo com `chave=valor` na seção
# [Appearance]. MERGE de verdade, linha a linha: toda outra chave (dela ou do
# daemon — color_scheme_path, custom_palette, cosmic_qt_version,
# standard_dialogs) sai intacta e na mesma ordem.
#
# As linhas em branco ficam num buffer para que a chave nova entre ANTES delas,
# e não depois: sem isso a chave caía entre a linha vazia e o `[Fonts]`
# seguinte. É válido para o QSettings, mas rende um diff torto na config dela
# — e config torta é o tipo de coisa que ninguém confere de novo.
_meow_tk_ini_definir() {
  local arquivo="${1:-}" chave="${2:-}" valor="${3:-}"
  if [ ! -r "$arquivo" ]; then
    printf '[Appearance]\n%s=%s\n' "$chave" "$valor"
    return 0
  fi
  MEOW_INI_CHAVE="$chave" MEOW_INI_VALOR="$valor" awk '
    BEGIN { chave = ENVIRON["MEOW_INI_CHAVE"]; valor = ENVIRON["MEOW_INI_VALOR"]
            posto = 0; na = 0; viu = 0; nbuf = 0 }
    function despejar(   i) { for (i = 1; i <= nbuf; i++) print buf[i]; nbuf = 0 }
    function por() { if (!posto) { print chave "=" valor; posto = 1 } }
    /^\[/ {
      if (na) por()
      despejar()
      na = ($0 == "[Appearance]"); if (na) viu = 1
      print; next
    }
    /^[ \t]*$/ { buf[++nbuf] = $0; next }
    {
      despejar()
      # troca no lugar, preservando a posição original da chave
      if (na && index($0, chave "=") == 1) { por(); next }
      print
    }
    END {
      if (na) por()
      vazias = nbuf
      despejar()
      if (!viu) {
        if (!vazias && NR > 0) print ""
        printf "[Appearance]\n%s=%s\n", chave, valor
      }
    }
  ' "$arquivo"
}

# --- backup (regra 4: antes de sobrescrever, SEMPRE) ------------------------
# O caminho dentro do backup é RELATIVO AO HOME, e isso não é enfeite: é a
# armadilha 2 do cabeçalho (dois `gtk.css` disputando o mesmo nome). O
# `origens.txt` existe porque sem o caminho absoluto original um "desfazer" não
# saberia para onde devolver o arquivo.
#
# `cp -P` é OBRIGATÓRIO: sem ele um symlink viraria cópia do alvo, e restaurar
# esse backup mataria a regeneração do COSMIC — que é exatamente o defeito que
# este módulo existe para consertar.
#
# O carimbo usa hífen (`%Y-%m-%dT%H-%M-%S`) e não `date -Iseconds` porque a
# pasta `backups/` é COMPARTILHADA por todos os módulos: em ASCII o `-` (0x2D)
# vem antes do `:` (0x3A), então misturar os dois formatos faria toda pasta com
# hífen parecer mais antiga que qualquer uma com dois pontos. `MEOW_CARIMBO` é
# a variável que os módulos vizinhos usam para caírem todos na mesma pasta.
_meow_tk_backup() {
  local origem="${1:-}" rel="" destino=""
  # `-L` junto com `-e` para que um symlink QUEBRADO também seja preservado.
  [ -e "$origem" ] || [ -L "$origem" ] || return 0
  meow_seco && return 0
  if [ -z "$MEOW_TK_BACKUP_DIR" ]; then
    MEOW_TK_BACKUP_DIR="${MEOW_ESTADO:-$HOME/.local/state/meowsystem}/backups/${MEOW_CARIMBO:-$(date +%Y-%m-%dT%H-%M-%S)}"
  fi
  case "$origem" in
    "$HOME"/*) rel="${origem#"$HOME"/}" ;;
    *)         rel="fora-da-home/${origem#/}" ;;
  esac
  destino="$MEOW_TK_BACKUP_DIR/$rel"
  mkdir -p "$(dirname "$destino")" || return 1
  cp -P --preserve=all -- "$origem" "$destino" || return 1
  printf '%s\n' "$origem" >> "$MEOW_TK_BACKUP_DIR/origens.txt" || return 1
  # Soma só de arquivo comum: `sha256sum` num symlink seguiria o alvo (e num
  # link quebrado falharia), transformando um backup fiel em erro de execução.
  if [ ! -L "$origem" ] && [ -f "$origem" ]; then
    ( cd "$MEOW_TK_BACKUP_DIR" && sha256sum -- "$rel" >> manifesto.sha256 ) || return 1
  fi
  meow_info "backup: $destino"
  return 0
}

# Qual css o COSMIC gerou (o alvo legítimo dos symlinks). Escuro primeiro.
_meow_tk_css_gerado() {
  local c
  for c in "$MEOW_TK_COSMIC_CSS_DIR/dark.css" "$MEOW_TK_COSMIC_CSS_DIR/light.css"; do
    if [ -r "$c" ]; then printf '%s' "$c"; return 0; fi
  done
  return 1
}

# Classifica o gtk.css em UMA palavra. É esta função que mantém `conferir` e
# `aplicar` enxergando a mesma realidade (armadilha 1 do cabeçalho):
#
#   ok                 symlink para o css que o COSMIC gera — nada a fazer
#   link-quebrado      symlink certo, alvo ainda não gerado — é com o COSMIC
#   link-alheio        symlink para outro lugar — escolha dela, não se toca
#   arquivo-igual      arquivo comum, byte a byte igual ao css gerado (típico
#                      de backup restaurado por cima) — ISTO nós religamos
#   arquivo-proprio    arquivo comum com conteúdo diferente — pode ser css dela
#   arquivo-sem-fonte  arquivo comum e não há css gerado para comparar
#   ausente            não existe — quem cria é o COSMIC
_meow_tk_gtk_estado() {
  local css="${1:-}" alvo="" gerado=""
  if [ -L "$css" ]; then
    alvo="$(readlink -m -- "$css")"
    case "$alvo" in
      "$MEOW_TK_COSMIC_CSS_DIR"/*.css)
        if [ -e "$css" ]; then printf 'ok'; else printf 'link-quebrado'; fi ;;
      *) printf 'link-alheio' ;;
    esac
    return 0
  fi
  if [ ! -e "$css" ]; then printf 'ausente'; return 0; fi
  if ! gerado="$(_meow_tk_css_gerado)"; then printf 'arquivo-sem-fonte'; return 0; fi
  if cmp -s "$css" "$gerado"; then printf 'arquivo-igual'; else printf 'arquivo-proprio'; fi
  return 0
}

# `gtk-3.0/gtk.css` em vez do caminho absoluto: as mensagens ficam legíveis e
# ainda dá para distinguir os dois de relance.
_meow_tk_curto() { printf '%s/%s' "$(basename "$(dirname "${1:-}")")" "$(basename "${1:-}")"; }

_meow_tk_qt_presente() { meow_tem qt5ct || meow_tem qt6ct; }

